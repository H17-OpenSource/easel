def test_experience_below_three_verdicts_is_shown_but_not_used(home: Path, capsys) -> None:
    run = home / "runs" / "run-20300101-002"
    shutil.copytree(home / "runs" / "run-20300101-001", run)
    manifest = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
    manifest["run"] = "run-20300101-002"
    manifest["resources"] = [{**r, "weight": 0.5} if r["role"] == "lora" else r for r in manifest["resources"]]
    manifest["resources"][1]["resource"] = INK
    (run / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    lines = [json.loads(line) for line in (run / "reviews.jsonl").read_text(encoding="utf-8").splitlines()][:2]
    (run / "reviews.jsonl").write_text("".join(json.dumps({**r, "run": "run-20300101-002"}) + "\n" for r in lines),
                                       encoding="utf-8")
    code, out, _err = run_cli(["standards", "explain", INK], capsys)
    assert code == 0
    lines = out.splitlines()
    at = lines.index(next(line for line in lines if line.startswith("weight: ")))
    assert lines[at].endswith(" from author")  # the LoRA's recommended weight range, not the 2-verdict experience
    assert lines[at + 2].startswith("  experience  0.5 (n=2, below 3: not used)")


