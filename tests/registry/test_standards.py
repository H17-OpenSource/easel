def test_set_and_unset_a_manual_value(home: Path, capsys) -> None:
    assert run_cli(["standards", "build"], capsys)[0] == 0
    code, out, err = run_cli(["standards", "set", ANIME_XL, "cfg", "6", "--note", "the operator: 6 looks cleaner"],
                             capsys)
    assert code == 0, err
    assert out.splitlines() == [f"{ANIME_XL}: manual cfg = 6 (the operator: 6 looks cleaner)",
                                "cfg now comes from manual: 6"]
    assert _card(home, ANIME_XL)["chosen"]["cfg"] == {"value": 6, "source": "manual"}
    last = json.loads((home / "registry" / "changelog.jsonl").read_text(encoding="utf-8").splitlines()[-1])
    assert (last["action"], last["source"], last["target"]) == ("set", "operator", {"kind": "card", "id": ANIME_XL})
    assert last["changes"] == {"manual.cfg": {"from": None, "to": 6}}
    # a rebuild keeps it
    assert run_cli(["standards", "build"], capsys)[0] == 0
    assert _card(home, ANIME_XL)["chosen"]["cfg"]["source"] == "manual"
    code, out, _err = run_cli(["standards", "unset", ANIME_XL, "cfg"], capsys)
    assert code == 0 and out.splitlines() == [f"{ANIME_XL}: manual cfg removed", "cfg now comes from experience: 5.5"]
    code, _out, err = run_cli(["standards", "unset", ANIME_XL, "cfg"], capsys)
    assert code == 2 and "has no manual cfg" in err


