def test_explain_shows_all_five_sources_per_field(home: Path, capsys) -> None:
    code, out, _err = run_cli(["standards", "explain", ROBOT], capsys)
    assert code == 0
    lines = out.splitlines()
    assert lines[0] == f"{ROBOT} demo_robot-v1.safetensors (lora, family illustrious, class sfw)"
    assert lines[1].startswith(f"card: standards/cards/{ROBOT}.yaml")
    assert lines[2].startswith("precedence: manual > experience > author > references > prior")
    heads = [i for i, line in enumerate(lines) if not line.startswith(" ") and ": " in line][3:]
    assert heads, out
    for i in heads:
        assert [lines[i + k].split()[0] for k in range(1, 6)] == list(cards.PRECEDENCE)
    weight = lines.index("weight: 0.8 from manual")
    assert lines[weight + 1].startswith("  manual      0.8") and "set by the person" in lines[weight + 1]
    assert lines[weight + 2].startswith("  experience  0.8 (n=4)") and "3 kept / 4 reviewed" in lines[weight + 2]
    assert lines[weight + 3].startswith("  author      0.7-0.9")
    assert lines[weight + 4] == "  references  -"
    assert lines[weight + 5].startswith("  prior       0.8") and "inference.lora_default_weight" in lines[weight + 5]
    code, out, _err = run_cli(["standards", "explain", ROBOT, "--json"], capsys)
    data = json.loads(out)
    assert data["chosen"]["weight"] == {"value": 0.8, "source": "manual"}
    assert list(data["fields"]["weight"]) == list(cards.PRECEDENCE) and data["fields"]["weight"]["references"] is None


