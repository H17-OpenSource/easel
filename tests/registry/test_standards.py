def test_author_text_first_match_wins_and_variants_are_skipped() -> None:
    text = "\n".join([
        "Recommended: CFG 5-7, Steps: 28, Sampler: DPM++ 2M Karras",
        "Size 832x1216, clip skip 2",
        "Hires fix: denoise 0.35, CFG 9",
        "ADetailer steps 12",
        "Use <lora:demo_robot:0.8> or weight 0.6-0.9",
        "CFG 12",
    ])
    lora = author.parse(text, "lora")
    assert lora["cfg"][0] == {"min": 5.0, "max": 7.0}
    assert lora["steps"][0] == 28 and lora["sampler"][0] == "dpmpp_2m" and lora["scheduler"][0] == "karras"
    assert (lora["width"][0], lora["height"][0], lora["clip_skip"][0]) == (832, 1216, 2)
    assert lora["hires_denoise"][0] == 0.35
    assert lora["weight"][0] == 0.8
    assert lora["cfg"][1].startswith("Recommended: CFG 5-7")
    assert "weight" not in author.parse(text, "checkpoint")


def test_sampler_names() -> None:
    assert author.normalise_sampler("Euler a") == ("euler_ancestral", None)
    assert author.normalise_sampler("DPM++ 2M SDE Karras") == ("dpmpp_2m_sde", "karras")
    assert author.normalise_sampler("demo-sampler") == (None, None)


