def test_build_writes_valid_cards_and_keeps_the_manual_entry(home: Path, capsys) -> None:
    code, out, err = run_cli(["standards", "build"], capsys)
    assert code == 0, err
    assert out.splitlines()[0] == "standards build: 4 card(s) written, 0 unchanged, under standards/cards/"
    assert "1 run(s) with 4 current verdict(s)" in out
    written = sorted(p.stem for p in (home / "standards" / "cards").glob("*.yaml"))
    assert written == sorted([ANIME_XL, BASE_XL, ROBOT, INK])
    for sha in written:
        card = _card(home, sha)
        assert schema_errors("usage-card", card) == [] and card["resource"] == sha
        text = (home / "standards" / "cards" / f"{sha}.yaml").read_text(encoding="utf-8")
        assert text.startswith("# Generated by `easel standards build`; do not edit")
    robot = _card(home, ROBOT)
    assert robot["chosen"]["weight"] == {"value": 0.8, "source": "manual"}
    manual = [v for v in robot["values"] if v["source"] == "manual"]
    assert manual == [{"field": "weight", "source": "manual", "value": 0.8, "evidence": "set by the person",
                       "n": None, "updated_at": "2030-01-01T13:00:00+00:00"}]
    experience = {v["field"]: v for v in robot["values"] if v["source"] == "experience"}
    assert experience["weight"]["value"] == 0.8 and experience["weight"]["n"] == 4  # 3 kept of 4 current verdicts
    assert experience["keep_rate"]["value"] == 0.75
    anime = _card(home, ANIME_XL)
    assert anime["chosen"]["cfg"] == {"value": 5.5, "source": "experience"}
    assert anime["chosen"]["prefix"]["source"] == "prior"
    refs = [v for v in anime["values"] if v["source"] == "references"]
    assert {v["field"] for v in refs} >= {"cfg", "steps", "sampler"}
    assert _card(home, INK)["chosen"]["weight"]["source"] == "author"  # its recommended weight range


