"""The usage cards: precedence, the files, and the five verbs (build, explain, report, set, unset).

A card is `<home>/standards/cards/<sha16>.yaml` (schema easel/usage-card/1): one entry per (field, source) and,
under `chosen`, the winner per field. `build` regenerates every source but manual from the evidence and keeps
the manual entries of the card it replaces; `set` and `unset` change only manual entries (and say so in
`registry/changelog.jsonl`, kind `card`). A card is rewritten only when a value changed, and a value keeps its
`updated_at` while it stays the same, so an unchanged library rebuilds without touching a file.

Precedence: manual > experience (only from MIN_EXPERIENCE verdicts on) > author > references > prior.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from easel._common import ids, store
from easel.registry import resources as res
from easel.registry.shipped import DataError, reason, schema_errors

from .sources import Gathered, Value, gather

CARD_SCHEMA = "easel/usage-card/1"
PRECEDENCE = ("manual", "experience", "author", "references", "prior")
MIN_EXPERIENCE = 3
FIELD_ORDER = ("weight", "cfg", "steps", "sampler", "scheduler", "clip_skip", "width", "height", "prefix",
               "negative", "trigger", "hires_denoise", "keep_rate")
TEXT_FIELDS = ("prefix", "negative", "trigger")  # prompt text: withheld for a class that is not sfw under sfw-only
REPORT_TYPES = ("checkpoint", "lora", "lycoris", "embedding")
FIELD_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
HEADER = "# Generated by `easel standards build`; do not edit (set a manual value with `easel standards set`).\n"
_RANGE = re.compile(r"^\s*(-?\d+(?:\.\d+)?)\s*(?:-|\.\.)\s*(-?\d+(?:\.\d+)?)\s*$")


# --- precedence -------------------------------------------------------------------------------------------------

def counts(value: Value) -> bool:
    """Whether a value may win: experience needs MIN_EXPERIENCE verdicts, every other source always may."""
    return value.source != "experience" or (value.n or 0) >= MIN_EXPERIENCE


def field_key(name: str) -> tuple:
    return (FIELD_ORDER.index(name) if name in FIELD_ORDER else len(FIELD_ORDER), name)


def choose(values: Iterable[Value]) -> dict[str, dict]:
    """{field: {value, source}}: per field the first source in PRECEDENCE whose value counts."""
    by_field: dict[str, dict[str, Value]] = {}
    for v in values:
        if counts(v):
            by_field.setdefault(v.field, {}).setdefault(v.source, v)
    chosen = {}
    for name in sorted(by_field, key=field_key):
        source = next(s for s in PRECEDENCE if s in by_field[name])
        chosen[name] = {"value": by_field[name][source].value, "source": source}
    return chosen


def sort_values(values: Iterable[Value]) -> list[Value]:
    return sorted(values, key=lambda v: (*field_key(v.field), PRECEDENCE.index(v.source)))


def parse_value(raw: str) -> object:
    """A value as `set` takes it: `0.6-0.8` -> {min, max}; JSON (a number, true, a quoted string); else the text."""
    match = _RANGE.match(raw)
    if match:
        a, b = float(match.group(1)), float(match.group(2))
        return {"min": min(a, b), "max": max(a, b)}
    try:
        return json.loads(raw)
    except ValueError:
        return raw.strip()


def shown_value(value: object) -> str:
    if isinstance(value, Mapping) and "min" in value and "max" in value:
        return f"{value['min']:g}-{value['max']:g}" if all(isinstance(value[k], int | float)
                                                          for k in ("min", "max")) else json.dumps(value)
    if isinstance(value, str):
        return value
    return json.dumps(value, ensure_ascii=False)


# --- card files -------------------------------------------------------------------------------------------------

def cards_dir(reg: res.Registry) -> Path:
    return reg.standards / "cards"


def card_path(reg: res.Registry, sha16: str) -> Path:
    return cards_dir(reg) / f"{sha16}.yaml"


def load_card(reg: res.Registry, sha16: str) -> dict | None:
    """The card of one resource, or None; DataError (exit 2) for a file that is not a valid card."""
    path = card_path(reg, sha16)
    if not path.is_file():
        return None
    try:
        data = store.read_record(path, "easel/usage-card/")
    except (OSError, ValueError, yaml.YAMLError) as exc:
        raise DataError([f"{reg.shown(path)}: not readable: {reason(exc)}"]) from exc
    errors = schema_errors("usage-card", data)
    if errors or data.get("resource") != sha16:
        raise DataError([f"{reg.shown(path)}: not a valid {CARD_SCHEMA} card of {sha16}: "
                         f"{(errors or ['resource differs from the file name'])[0]}"])
    return data


def card_values(card: Mapping | None, source: str | None = None) -> list[tuple[Value, str | None]]:
    """(value, updated_at) for each entry of a card (only `source`'s when given)."""
    out = []
    for e in (card or {}).get("values") or []:
        if source is None or e.get("source") == source:
            out.append((Value(e["field"], e["source"], e["value"], e.get("evidence"), e.get("n")),
                        e.get("updated_at")))
    return out


def make_card(sha16: str, values: Iterable[Value], old: Mapping | None, now: str) -> dict:
    """The card for `values`; an entry unchanged since `old` keeps its updated_at, and so does the card."""
    previous = {(v.field, v.source, json.dumps(v.value, sort_keys=True), v.evidence, v.n): at
                for v, at in card_values(old)}
    entries = []
    ordered = sort_values(values)
    for v in ordered:
        key = (v.field, v.source, json.dumps(v.value, sort_keys=True), v.evidence, v.n)
        entries.append({"field": v.field, "source": v.source, "value": v.value, "evidence": v.evidence, "n": v.n,
                        "updated_at": previous.get(key) or now})
    card = {"schema": CARD_SCHEMA, "resource": sha16, "generated_at": now, "values": entries,
            "chosen": choose(ordered)}
    if old is not None and _same(old, card):
        card["generated_at"] = old.get("generated_at") or now
    return card


def _same(a: Mapping, b: Mapping) -> bool:
    return (json.dumps(a.get("values"), sort_keys=True) == json.dumps(b.get("values"), sort_keys=True)
            and json.dumps(a.get("chosen"), sort_keys=True) == json.dumps(b.get("chosen"), sort_keys=True))


def write_card(reg: res.Registry, card: Mapping) -> Path:
    """Validate and write one card atomically (with the do-not-edit line); DataError when it fails the schema."""
    data = {"schema": CARD_SCHEMA, **{k: v for k, v in card.items() if k != "schema"}}
    errors = schema_errors("usage-card", data)
    if errors:
        raise DataError([f"card {data.get('resource')}: not written, it fails {CARD_SCHEMA}:"] +
                        [f"  {e}" for e in errors])
    return store.write_text(card_path(reg, str(data["resource"])), HEADER + store.dump_yaml(data))


def _records(reg: res.Registry) -> tuple[dict[str, dict], list[str]]:
    loaded = res.load_records(reg)
    return res.effective(loaded.records, res.load_overrides(reg)), [f"warning: {p}" for p in loaded.problems]


# --- build ------------------------------------------------------------------------------------------------------

@dataclass
class BuildReport:
    """What `build` did."""

    written: list[str] = field(default_factory=list)
    unchanged: int = 0
    by_source: dict[str, int] = field(default_factory=dict)
    manual_kept: int = 0
    gathered: Gathered | None = None
    warnings: list[str] = field(default_factory=list)

    def lines(self, reg: res.Registry) -> list[str]:
        g = self.gathered or Gathered()
        sources = ", ".join(f"{s} {self.by_source.get(s, 0)}" for s in PRECEDENCE)
        return [f"standards build: {len(self.written)} card(s) written, {self.unchanged} unchanged, under "
                f"{reg.shown(cards_dir(reg))}/",
                f"values by source: {sources} (manual kept from the cards: {self.manual_kept})",
                f"evidence: {g.runs} run(s) with {g.verdicts} current verdict(s); {g.references} reference(s), "
                f"{g.linked} resource mention(s) linked; experience counts from {MIN_EXPERIENCE} verdicts on"]


def build(reg: res.Registry, cfg) -> BuildReport:
    """Rebuild every card from the evidence, keeping each card's manual entries."""
    report = BuildReport()
    records, report.warnings = _records(reg)
    gathered = gather(reg, cfg, records)
    report.gathered = gathered
    report.warnings += [f"warning: {p}" for p in gathered.problems]
    now = ids.now_iso(reg.tool)
    with store.lock(reg.registry, reg.tool):
        for sha in sorted(records):
            old = load_card(reg, sha)
            manual = [v for v, _at in card_values(old, "manual")]
            values = manual + gathered.values.get(sha, [])
            if not values and old is None:
                continue
            report.manual_kept += len(manual)
            for v in values:
                report.by_source[v.source] = report.by_source.get(v.source, 0) + 1
            card = make_card(sha, values, old, now)
            if old is not None and _same(old, card):
                report.unchanged += 1
                continue
            write_card(reg, card)
            report.written.append(sha)
    return report


# --- set / unset ------------------------------------------------------------------------------------------------

def _resolve(reg: res.Registry, text: str) -> tuple[str, dict]:
    records, _warnings = _records(reg)
    sha = res.resolve_id(records, text)
    return sha, records[sha]


def set_manual(reg: res.Registry, cfg, sha_text: str, name: str, raw: str, note: str,
               by: str = "easel standards set") -> list[str]:
    """Record the person's value for one field; the card's other entries stay as they are."""
    if not FIELD_NAME.match(name):
        raise LookupError(f"not a field name (lower case, digits, _): {name!r}")
    if not note or not note.strip():
        raise LookupError("--note is required: the person's reason, in their words")
    sha, _record = _resolve(reg, sha_text)
    value = parse_value(raw)
    now = ids.now_iso(reg.tool)
    with store.lock(reg.registry, reg.tool):
        old = load_card(reg, sha)
        before = next((v.value for v, _at in card_values(old, "manual") if v.field == name), None)
        kept = [v for v, _at in card_values(old) if not (v.source == "manual" and v.field == name)]
        card = make_card(sha, [*kept, Value(name, "manual", value, note.strip())], old, now)
        write_card(reg, card)
    res.append_changelog(reg, [res.changelog_line(tool=reg.tool, source="operator", by=by, action="set",
                                                  kind="card", target=sha,
                                                  changes={f"manual.{name}": {"from": before, "to": value}},
                                                  note=note.strip())])
    lines = [f"{sha}: manual {name} = {shown_value(value)} ({note.strip()})",
             f"{name} now comes from {card['chosen'][name]['source']}: {shown_value(card['chosen'][name]['value'])}"]
    if name not in FIELD_ORDER:
        lines.append(f"note: {name} is not one of the fields recipes read ({', '.join(FIELD_ORDER)})")
    return lines


def unset_manual(reg: res.Registry, cfg, sha_text: str, name: str, note: str | None = None,
                 by: str = "easel standards unset") -> list[str]:
    """Remove the person's value for one field; the next source in the precedence takes over."""
    sha, _record = _resolve(reg, sha_text)
    now = ids.now_iso(reg.tool)
    with store.lock(reg.registry, reg.tool):
        old = load_card(reg, sha)
        before = next((v.value for v, _at in card_values(old, "manual") if v.field == name), None)
        if old is None or not any(v.field == name for v, _at in card_values(old, "manual")):
            raise LookupError(f"{sha} has no manual {name}; `easel standards explain {sha}` shows its values")
        kept = [v for v, _at in card_values(old) if not (v.source == "manual" and v.field == name)]
        card = make_card(sha, kept, old, now)
        write_card(reg, card)
    res.append_changelog(reg, [res.changelog_line(tool=reg.tool, source="operator", by=by, action="unset",
                                                  kind="card", target=sha,
                                                  changes={f"manual.{name}": {"from": before, "to": None}},
                                                  note=(note or "").strip() or None)])
    winner = card["chosen"].get(name)
    after = (f"{name} now comes from {winner['source']}: {shown_value(winner['value'])}" if winner
             else f"{name} has no value from any source now")
    return [f"{sha}: manual {name} removed", after]


# --- explain ----------------------------------------------------------------------------------------------------

def explain(reg: res.Registry, cfg, sha_text: str, *, as_json: bool = False) -> list[str] | dict:
    """All five sources for every field of one resource, from the evidence as it is now (and the card's manual)."""
    records, _warnings = _records(reg)
    sha = res.resolve_id(records, sha_text)
    record = records[sha]
    card = load_card(reg, sha)
    values = [v for v, _at in card_values(card, "manual")] + gather(reg, cfg, records, only=[sha]).values.get(sha, [])
    chosen = choose(values)
    by_field: dict[str, dict[str, Value]] = {}
    for v in values:
        by_field.setdefault(v.field, {}).setdefault(v.source, v)
    if as_json:
        return {"resource": sha, "chosen": chosen,
                "fields": {f: {s: (None if s not in srcs else {"value": srcs[s].value, "evidence": srcs[s].evidence,
                                                              "n": srcs[s].n, "counts": counts(srcs[s])})
                               for s in PRECEDENCE} for f, srcs in by_field.items()}}
    authoring = str(cfg.get("policy.prompt_authoring", "sfw-only"))
    klass = res.get_field(record, "semantics.content.class")
    withhold = authoring == "sfw-only" and klass != "sfw"
    name = res.get_field(record, "identity.file_name")
    lines = [f"{sha} {name} ({res.get_field(record, 'identity.type')}, family "
             f"{res.get_field(record, 'identity.family') or 'unknown'}, class {klass})"]
    if card is None:
        lines.append(f"card: not built yet; `easel standards build` writes {reg.shown(card_path(reg, sha))}")
    else:
        lines.append(f"card: {reg.shown(card_path(reg, sha))} (built {card.get('generated_at')})")
    lines.append(f"precedence: {' > '.join(PRECEDENCE)}; experience counts from {MIN_EXPERIENCE} verdicts on; "
                 "the first source that counts wins")
    if not by_field:
        lines.append("no usage values from any source yet")
        return lines

    def text(v: Value) -> str:
        if withhold and v.field in TEXT_FIELDS and isinstance(v.value, str):
            return f"(text withheld: class {klass})"
        return shown_value(v.value)

    for fname in sorted(by_field, key=field_key):
        srcs = by_field[fname]
        win = chosen.get(fname)
        head = (f"{fname}: {text(srcs[win['source']])} from {win['source']}" if win
                else f"{fname}: no source counts yet")
        lines.append(head)
        for s in PRECEDENCE:
            v = srcs.get(s)
            if v is None:
                lines.append(f"  {s:<10}  -")
                continue
            notes = [f"n={v.n}"] if v.n is not None else []
            if not counts(v):
                notes.append(f"below {MIN_EXPERIENCE}: not used")
            shown = f"{text(v)} ({', '.join(notes)})" if notes else text(v)
            lines.append(f"  {s:<10}  {shown:<24}  {v.evidence or ''}".rstrip())
    return lines


# --- report -----------------------------------------------------------------------------------------------------

def report(reg: res.Registry) -> list[str]:
    """A Markdown table over the checkpoints, LoRAs and embeddings: which sources each card holds."""
    records, _warnings = _records(reg)
    rows = []
    coverage: dict[str, int] = {}
    shown = [r for r in sorted(records.values(), key=res.sort_key) if res.get_field(r, "identity.type") in REPORT_TYPES]
    for rec in shown:
        sha = str(rec["id"])
        card = load_card(reg, sha)
        sources = [s for s in PRECEDENCE if any(v.source == s for v, _at in card_values(card))]
        for s in sources:
            coverage[s] = coverage.get(s, 0) + 1
        klass = res.get_field(rec, "semantics.content.class")
        name = (f"{res.get_field(rec, 'identity.file_name')} (`{sha}`)" if klass == "sfw" else f"`{sha}`")
        rows.append(f"| {res.get_field(rec, 'identity.type')} | {res.get_field(rec, 'identity.family') or '?'} | "
                    f"{res.get_field(rec, 'semantics.content.rating')} | {name} | {', '.join(sources) or '-'} | "
                    f"{len((card or {}).get('chosen') or {})} |")
    cover = ", ".join(f"{s} {coverage[s]}" for s in PRECEDENCE if coverage.get(s)) or "no cards yet"
    return ["# Usage standards", "",
            "Generated by `easel standards report` from the cards `easel standards build` writes. The value that "
            "wins for a field, with all five sources: `easel standards explain <sha16>`.", "",
            "| type | family | rating | resource | sources | fields |", "|---|---|---|---|---|---:|", *rows, "",
            f"Coverage over {len(rows)} resource(s): {cover}. Resources that are not sfw are named by id only."]
