"""`easel lessons add|list|render`: the argparse layer over `easel.lessons`.

Exit codes: 0 ok; 1 `render` refused to overwrite a page it did not generate; 2 usage, configuration or data
error; 4 the lessons lock is held by another process.
"""

from __future__ import annotations

import argparse
import json
import sys

HELP = "record a lesson as finding, evidence and rule; render the lessons docs"


def register(subparsers: argparse._SubParsersAction) -> None:
    """Add `lessons` and its actions."""
    from easel._common.config import add_workspace_arg
    from easel.lessons import ORIGINS

    parser = subparsers.add_parser(
        "lessons", help=HELP,
        description="Lessons learned: one line per lesson in <home>/lessons/entries.jsonl (finding, evidence, the "
                    "rule it implies), rendered into one page per model family with `lessons render`.")
    actions = parser.add_subparsers(dest="action", metavar="<action>", title="actions")

    add = actions.add_parser(
        "add", help="record one lesson: what was found, the evidence, the rule it implies",
        description="Append one lesson. Write the operator's words; a finding of your own needs --assistant. "
                    "Feedback the operator copied from a model page by hand is --source civitai (comments are "
                    "never read by a tool).")
    add.add_argument("--family", metavar="<family>", help="the model family it holds for (a families/<id>.yaml "
                                                          "stem); leave it out for a lesson that holds for every family")
    add.add_argument("--finding", required=True, help="what was found, in one sentence")
    add.add_argument("--evidence", required=True, help="what shows it: run ids, output numbers, counts, dates")
    add.add_argument("--rule", required=True, help="what to do from now on")
    add.add_argument("--topic", help="a short topic, for example \"lora weight\"")
    add.add_argument("--source", choices=ORIGINS, default="manual",
                     help="where the finding came from (default manual); civitai = feedback copied by hand")
    add.add_argument("--recorded-in", metavar="<file>", help="the runbook or doc row the lesson also went into")
    add.add_argument("--assistant", action="store_true",
                     help="the finding is the assistant's own, stored under policy.second_source_name, not the "
                          "operator's words")
    add_workspace_arg(add)
    add.set_defaults(func=_add)

    lst = actions.add_parser("list", help="one line per lesson: id | family | origin | rule",
                             description="One line per lesson, oldest first.")
    lst.add_argument("--family", metavar="<family>", help="only this family")
    lst.add_argument("--json", action="store_true", help="the lesson lines as a JSON list")
    add_workspace_arg(lst)
    lst.set_defaults(func=_list)

    render = actions.add_parser(
        "render", help="write <family>.md per family: Finding | Evidence | Rule | Recorded in",
        description="Write one generated page per family (general.md for lessons without one) into "
                    "<home>/lessons/ or --out. A page that was not generated by this command is never overwritten.")
    render.add_argument("--out", metavar="<dir>", help="the folder to write into (default: the instance's lessons "
                                                        "folder); scan with `easel privacy scan --public` before "
                                                        "you contribute pages to a repository")
    render.add_argument("--family", metavar="<family>", help="only this family's page")
    add_workspace_arg(render)
    render.set_defaults(func=_render)


def _err(lines) -> None:
    for line in lines:
        print(line, file=sys.stderr)


def _guarded(handler):
    """Map the known failures to their exit codes; a held lock is journalled, then re-raised (exit 4)."""

    def run(args: argparse.Namespace) -> int:
        from easel._common import store
        from easel._common.config import ConfigError
        from easel.lessons import LessonError
        from easel.registry.shipped import DataError

        try:
            return handler(args)
        except ConfigError as exc:
            _err(exc.lines)
            return exc.code
        except (LessonError, DataError) as exc:
            _err(exc.lines)
            return 2
        except store.Held as held:
            _journal_held(args, held)
            raise

    run.__doc__ = handler.__doc__
    return run


def _journal_held(args: argparse.Namespace, held) -> None:
    try:
        from easel._common import config, journal

        cfg = config.load(args.tool, args.workspace, strict=False)
        journal.note(f"stuck: {held.line}", tool=args.tool, journal_dir=cfg.path("paths.journal"), timeout=2.0)
    except Exception:  # noqa: BLE001  (journalling a held lock must never hide the exit 4)
        pass


def _open(args: argparse.Namespace):
    from easel import lessons
    from easel._common import config

    cfg = config.load(args.tool, args.workspace, strict=True)
    return cfg, lessons.lessons_dir(cfg)


@_guarded
def _add(args: argparse.Namespace) -> int:
    from easel import lessons
    from easel.registry.shipped import shown

    cfg, folder = _open(args)
    source = str(cfg.get("policy.second_source_name", "assistant")) if args.assistant else "operator"
    line = lessons.add(folder, finding=args.finding, evidence=args.evidence, rule=args.rule, family=args.family,
                       topic=args.topic, origin=args.source, recorded_in=args.recorded_in, source=source,
                       families=lessons.known_families(cfg.root), tool=args.tool)
    print(f"{line['id']} added to {shown(folder / lessons.ENTRIES, cfg.root)} "
          f"(family {line['family'] or '-'}, source {line['origin']}, recorded by {line['source']})")
    print("next: easel lessons render")
    return 0


@_guarded
def _list(args: argparse.Namespace) -> int:
    from easel import lessons

    _cfg, folder = _open(args)
    entries = [e for e in lessons.read(folder) if args.family is None or e.get("family") == args.family]
    if args.json:
        print(json.dumps(entries, indent=2, ensure_ascii=False))
        return 0
    for entry in entries:
        print(lessons.list_line(entry))
    print(f"{len(entries)} lesson{'' if len(entries) == 1 else 's'}")
    return 0


@_guarded
def _render(args: argparse.Namespace) -> int:
    from pathlib import Path

    from easel import lessons
    from easel.registry.shipped import shown

    cfg, folder = _open(args)
    pages = lessons.render(lessons.read(folder), family=args.family)
    out = Path(args.out).expanduser() if args.out else folder
    result = lessons.write_pages(out, pages, root=cfg.root)
    for path in result.written:
        print(f"wrote {shown(path, cfg.root)}")
    for path in result.unchanged:
        print(f"unchanged {shown(path, cfg.root)}")
    _err(result.refused)
    print(f"{len(pages)} page{'' if len(pages) == 1 else 's'}: {len(result.written)} written, "
          f"{len(result.unchanged)} unchanged, {len(result.refused)} refused")
    return 1 if result.refused else 0
