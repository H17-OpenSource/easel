"""Lessons learned: a finding, the evidence for it and the rule it implies, kept as an event log, rendered as docs.

Why: a verdict says what happened to one image; a lesson says what to do next time ("start the demo_robot LoRA at
0.8 on Illustrious checkpoints"). Writing it down with its evidence keeps the rule honest and lets a later session
(or a weaker model) apply it without re-learning it.

- `easel lessons add --family <f> --finding ... --evidence ... --rule ...` appends one line (easel/lessons-entry/1)
  to `<home>/lessons/entries.jsonl` under the store lock. `--source` says where the finding came from (`review`,
  `run`, `search`, `civitai` for feedback the person copied from a model page by hand, `manual`); the line's
  `source` says who recorded it: the operator, or the second source (`policy.second_source_name`) when the
  assistant states its own finding.
- `easel lessons render` writes one page per family, `<family>.md` (and `general.md` for lessons without a
  family), with the table Finding | Evidence | Rule | Recorded in. The default target is `<home>/lessons/`;
  `--out <dir>` writes elsewhere, for example a repository's `docs/lessons/` when the person contributes a lesson
  (scan it with `easel privacy scan --public` first). A page without the generated marker is never overwritten.

Lessons are never edited or deleted: a correction is a new lesson that says which one it corrects.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

from easel._common import ids, store
from easel.cli import instance_not_found, new_instance_hint
from easel.registry.shipped import REPO, schema_errors, shown

SCHEMA = "easel/lessons-entry/1"
ENTRIES = "entries.jsonl"
ORIGINS = ("review", "run", "search", "civitai", "manual")
GENERAL = "general"
MARKER = "<!-- generated by `easel lessons render` from lessons/entries.jsonl; do not edit: add a lesson instead -->"
COLUMNS = ("Finding", "Evidence", "Rule", "Recorded in")


class LessonError(Exception):
    """A lesson that cannot be written or rendered: `.lines` to print, exit 2."""

    def __init__(self, *lines: str) -> None:
        super().__init__("\n".join(lines))
        self.lines = list(lines)


def lessons_dir(cfg) -> Path:
    """`paths.lessons` of the instance (default `lessons`), relative to the instance root."""
    if cfg.get("paths.lessons", None) is not None:
        return cfg.path("paths.lessons")
    if cfg.root is None:
        raise LessonError(instance_not_found(), new_instance_hint())
    return cfg.root / "lessons"


def known_families(home: Path | None) -> set[str]:
    """Family ids: the stems of the shipped `families/*.yaml` and of the instance's own `<home>/families/*.yaml`."""
    folders = [REPO / "families"] + ([Path(home) / "families"] if home is not None else [])
    return {p.stem for folder in folders if folder.is_dir() for p in folder.glob("*.yaml")}


def _text(value: object, what: str) -> str:
    text = " ".join(str(value or "").split())
    if not text:
        raise LessonError(f"{what} is empty: a lesson needs a finding, its evidence and the rule it implies")
    return text


def read(folder: Path) -> list[dict]:
    """The lessons in `folder/entries.jsonl`, the latest line per id, in the order they were first added."""
    first: dict[str, int] = {}
    latest: dict[str, dict] = {}
    for n, rec in enumerate(store.read_jsonl(Path(folder) / ENTRIES).records):
        lid = rec.get("id")
        if not isinstance(lid, str):
            continue
        first.setdefault(lid, n)
        latest[lid] = rec
    return [latest[lid] for lid in sorted(latest, key=first.__getitem__)]


def add(folder: Path, *, finding: str, evidence: str, rule: str, family: str | None = None,
        topic: str | None = None, origin: str = "manual", recorded_in: str | None = None,
        source: str = "operator", families: Iterable[str] = (), tool: str = "easel") -> dict:
    """Append one lesson and return its line. The id is the next `les-YYYYMMDD-NNN`, claimed under the lock."""
    if origin not in ORIGINS:
        raise LessonError(f"--source {origin!r}: one of {', '.join(ORIGINS)}")
    known = set(families)
    if family is not None and known and family not in known:
        raise LessonError(f"unknown family {family!r}; families: {', '.join(sorted(known))}",
                          "leave --family out for a lesson that holds for every family")
    line = {"schema": SCHEMA, "at": None, "v": 1, "source": source, "by": "easel lessons add", "id": None,
            "family": family, "topic": " ".join(topic.split()) if topic else None,
            "finding": _text(finding, "--finding"), "evidence": _text(evidence, "--evidence"),
            "rule": _text(rule, "--rule"), "origin": origin, "recorded_in": recorded_in or None}
    folder = Path(folder)
    with store.lock(folder, tool):
        taken = [rec.get("id") for rec in store.read_jsonl(folder / ENTRIES).records if isinstance(rec.get("id"), str)]
        line["id"] = ids.next_seq_id("les", taken, tool)
        line["at"] = ids.now_iso(tool)
        problems = schema_errors("lessons-entry", line)
        if problems:
            raise LessonError(f"lesson not written: it fails {SCHEMA}:", *[f"  {p}" for p in problems])
        store.append_bytes_locked(folder / ENTRIES, (json.dumps(line, ensure_ascii=False) + "\n").encode("utf-8"))
    return line


# --- rendering -----------------------------------------------------------------------------------------------------

def _cell(value: object) -> str:
    return " ".join(str(value or "").split()).replace("|", "\\|")


def recorded_cell(entry: Mapping) -> str:
    """The Recorded in cell: the lesson id with its date and origin, then the doc row it also went into."""
    day = str(entry.get("at") or "")[:10]
    cell = f"{entry.get('id')} ({day}, {entry.get('origin')})"
    if entry.get("recorded_in"):
        cell += f"; {entry['recorded_in']}"
    return _cell(cell)


def page_name(family: str | None) -> str:
    return f"{family or GENERAL}.md"


def render_page(family: str | None, entries: Iterable[Mapping]) -> str:
    """One generated lessons page: title, the do-not-edit marker, the four-column table."""
    rows = list(entries)
    title = f"# Lessons: {family}" if family else f"# Lessons: {GENERAL} (no model family)"
    out = [title, "", MARKER, "",
           f"{len(rows)} lesson{'' if len(rows) == 1 else 's'}, oldest first. Each rule holds until a later lesson "
           "says otherwise.", "",
           "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    for entry in rows:
        finding = _cell(entry.get("finding"))
        if entry.get("topic"):
            finding = f"{_cell(entry['topic'])}: {finding}"
        out.append(f"| {finding} | {_cell(entry.get('evidence'))} | {_cell(entry.get('rule'))} | "
                   f"{recorded_cell(entry)} |")
    out.append("")
    return "\n".join(out)


def render(entries: Iterable[Mapping], family: str | None = None) -> dict[str, str]:
    """{page file name: text} for every family that has a lesson (or just `family`)."""
    groups: dict[str | None, list[Mapping]] = {}
    for entry in entries:
        groups.setdefault(entry.get("family"), []).append(entry)
    if family is not None:
        groups = {family: groups.get(family, [])}
    return {page_name(fam): render_page(fam, rows) for fam, rows in sorted(groups.items(), key=lambda kv: kv[0] or "")}


@dataclass
class Written:
    """What `write_pages` did: pages written, pages left as they were (same bytes), pages refused."""

    written: list[Path]
    unchanged: list[Path]
    refused: list[str]


def write_pages(out: Path, pages: Mapping[str, str], root: Path | None = None) -> Written:
    """Write the pages into `out`; a file that exists without the generated marker is refused, never replaced."""
    out = Path(out)
    result = Written([], [], [])
    for name, text in pages.items():
        target = out / name
        if target.exists():
            old = target.read_text(encoding="utf-8", errors="replace")
            if MARKER not in old:
                result.refused.append(f"refused: {shown(target, root)} was not generated by `easel lessons render`; "
                                      "it is never overwritten (render into another folder with --out)")
                continue
            if old == text:
                result.unchanged.append(target)
                continue
        store.write_text(target, text)
        result.written.append(target)
    return result


def list_line(entry: Mapping) -> str:
    """`les-... | family | origin | rule` for `lessons list`."""
    return f"{entry.get('id')} | {entry.get('family') or '-'} | {entry.get('origin')} | {_cell(entry.get('rule'))}"
