"""Generate the dependency tables of THIRD_PARTY_NOTICES.md from the installed packages' own metadata.

usage:
  python tools/gen_notices.py            rewrite the generated block of THIRD_PARTY_NOTICES.md
  python tools/gen_notices.py --check    exit 1 when the block differs from what would be written; write nothing

The block sits between the BEGIN and END marker lines; everything outside them is hand-written and kept as it
is. The tables come from `pip-licenses --from=mixed --format=markdown --with-urls --no-version --with-system
--packages ...` over the dependency closure of this checkout's package: first its core requirements, then what
the [dev] extra adds, read from the installed distribution's metadata. So run it where the checkout is
installed with `pip install -e ".[dev]"`. Names and licence strings are what each package declares (for example
Pillow's `MIT-CMU`); a dependency that installs only on some platforms is listed when it is installed here.

exit codes: 0 written or current; 1 differs (--check); 2 cannot run (a missing tool, package or marker).
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
NOTICES = REPO / "THIRD_PARTY_NOTICES.md"
BEGIN = "<!-- BEGIN generated by tools/gen_notices.py; edit outside these markers only -->"
END = "<!-- END generated by tools/gen_notices.py -->"
SKIP = {"pip", "setuptools", "wheel"}


class CannotRun(Exception):
    """A missing tool, package or marker; main prints it and exits 2."""


def package_of(repo: Path) -> str:
    found = sorted(d.name for d in (repo / "src").glob("*") if (d / "cli.py").is_file())
    if len(found) != 1:
        raise CannotRun("expected exactly one src/<package>/cli.py in this checkout")
    return found[0]


def requirements(name: str, extras: tuple[str, ...] = ()):
    """The requirements of one installed distribution whose markers hold here, for the given extras only."""
    try:
        from packaging.requirements import Requirement
    except ImportError as exc:
        raise CannotRun("the packaging module is missing; install the checkout with its [dev] extra") from exc
    try:
        raw = metadata.distribution(name).requires or []
    except metadata.PackageNotFoundError as exc:
        raise CannotRun(f"{name} is not installed here; run pip install -e \".[dev]\" first") from exc
    out = []
    for line in raw:
        req = Requirement(line)
        envs = [{"extra": extra} for extra in extras] if extras else [{"extra": ""}]
        if req.marker is None:
            if not extras:
                out.append(req)
        elif any(req.marker.evaluate(env) for env in envs):
            if extras and req.marker.evaluate({"extra": ""}):
                continue  # a core requirement with a platform marker, not something the extra adds
            out.append(req)
    return out


def canonical(name: str) -> str:
    from packaging.utils import canonicalize_name

    return str(canonicalize_name(name))


def closure(roots, own: str) -> list[str]:
    """Every installed distribution reachable from `roots`, by canonical name, without the package itself."""
    seen: dict[str, None] = {}
    todo = list(roots)
    while todo:
        req = todo.pop()
        name = canonical(req.name)
        if name in seen or name in SKIP or name == own:
            continue
        seen[name] = None
        todo.extend(requirements(name, tuple(sorted(req.extras))))
        if req.extras:
            todo.extend(requirements(name))
    return sorted(seen)


def table(names: list[str]) -> str:
    if not names:
        return "(none)\n"
    command = [sys.executable, "-m", "piplicenses", "--from=mixed", "--format=markdown", "--with-urls",
               "--no-version", "--with-system", "--packages", *names]
    try:
        done = subprocess.run(command, capture_output=True, text=True, timeout=300)
    except (OSError, subprocess.SubprocessError) as exc:
        raise CannotRun(f"pip-licenses could not run: {exc.__class__.__name__}") from exc
    if done.returncode != 0:
        raise CannotRun("pip-licenses failed; install the [dev] extra (pip-licenses>=5.0)")
    return "\n".join(line.rstrip() for line in done.stdout.strip().splitlines()) + "\n"


def generated_block(pkg: str) -> str:
    core = closure(requirements(pkg), pkg)
    dev = [name for name in closure(requirements(pkg, ("dev",)), pkg) if name not in core]
    return "\n".join([
        BEGIN,
        "",
        f"### Installed with {pkg} (core dependencies and what they pull in)",
        "",
        table(core),
        "### Installed with the [dev] extra (tests, lint, the licence gate)",
        "",
        table(dev) + END,
    ])


def render(text: str, block: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise CannotRun(f"{NOTICES.name} needs exactly one BEGIN and one END marker line, in that order")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen_notices.py", description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="compare with the file on disk; write nothing")
    args = parser.parse_args(argv)
    try:
        pkg = package_of(REPO)
        text = NOTICES.read_text(encoding="utf-8") if NOTICES.is_file() else ""
        if not text:
            raise CannotRun(f"{NOTICES.name} is missing; its hand-written part and the two markers come first")
        new = render(text, generated_block(pkg))
    except CannotRun as exc:
        print(f"gen_notices: {exc}", file=sys.stderr)
        return 2
    if args.check:
        if new != text:
            print(f"differ: {NOTICES.name}; run python tools/gen_notices.py")
            return 1
        print("current")
        return 0
    if new != text:
        NOTICES.write_text(new, encoding="utf-8", newline="\n")
        print(f"wrote {NOTICES.name}")
    else:
        print("current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
